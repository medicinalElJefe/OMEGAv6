import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {historicalImpulseSeedR678,replayHistoricalDonorR678,verifyOriginalDonorReplayR678,R678_DONOR_REPLAY_PROOF} from '../src7/workspaces/historicalOperatorReplayR678.js';
const expected=R678_DONOR_REPLAY_PROOF;
assert.equal(expected.claimedIterations,60);
assert.equal(expected.matchedEffectiveUpdates,59);
assert.equal(expected.archiveMetadataContradictionRetained,true);
const seed=historicalImpulseSeedR678();
assert.equal(seed.length,1728);
assert.ok(Math.abs(seed.reduce((a,b)=>a+b,0)-1)<1e-13);
assert.equal(seed.filter(v=>v>0).length,12);
const restored=replayHistoricalDonorR678(59),claimed=replayHistoricalDonorR678(60);
assert.equal(restored.ledger.length,59);
assert.equal(claimed.ledger.length,60);
assert.equal(restored.metadataDiscrepancy,true);
assert.equal(claimed.metadataDiscrepancy,false);
assert.equal(restored.canonicalMutation,false);
assert.ok(restored.values.every(v=>Number.isFinite(v)&&v>=0));
const digest=(values)=>createHash('sha256').update(Array.from(values,v=>v.toFixed(7)).join(',')).digest('hex');
assert.equal(digest(restored.values),expected.fullVectorSha256,'all 1728 replay values must match the real original archived CSV at seven decimals');
assert.notEqual(digest(claimed.values),expected.fullVectorSha256,'source declared T60 is provably one effective update beyond stored source result');
const verification=await verifyOriginalDonorReplayR678(restored.values);
assert.equal(verification.match,true);
assert.equal(verification.sha256,expected.fullVectorSha256);
assert.equal((await verifyOriginalDonorReplayR678(claimed.values)).match,false);
assert.deepEqual(restored,replayHistoricalDonorR678(59),'historical update must replay deterministically');
assert.throws(()=>replayHistoricalDonorR678(0));
assert.throws(()=>replayHistoricalDonorR678(61));
await assert.rejects(()=>verifyOriginalDonorReplayR678(new Float64Array(100)));
console.log('R678 PASS: original 1728-node Propagation_final_v9.csv full-vector SHA256 matched at 7 decimals after EXACTLY 59 effective updates; historical T60 off-by-one retained and tested');
