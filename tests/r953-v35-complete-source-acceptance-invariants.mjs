import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const proof=JSON.parse(readFileSync('audit/omega-v35-full-source-acceptance-r953.json','utf8'));
const source=JSON.parse(readFileSync('audit/omega-drive-historical-archive-source-index-r936.json','utf8'));
const ledger=JSON.parse(readFileSync('audit/omega-active-full-build-ledger-r937.json','utf8'));
const v35=source.groups.find(x=>x.id==='V35');
assert.equal(proof.schema,'OMEGA_V35_COMPLETE_SOURCE_BYTE_AUDIT_R953');
assert.equal(proof.sourcePartsVerified,20);
assert.equal(proof.sourcePartsExpected,20);
assert.equal(proof.parts.length,20);
assert.equal(proof.sourceWrapperCrcPasses,20);
assert.equal(proof.originalBasePayloadsVerified,17);
assert.equal(proof.originalExpansionArchivesVerified,3);
assert.equal(proof.innerSourceSHA256Matches,20);
assert.equal(proof.sourceDigestMismatches,0);
assert.equal(proof.sourceBytesVerified,v35.parts.reduce((n,p)=>n+p.bytes,0));
assert.match(proof.originalDeliveryManifestSha256,/^[a-f0-9]{64}$/);
assert.equal(proof.verifiedInstallerOnWindows,false);
assert.equal(proof.verifiedNativeGpu,false);
assert.equal(proof.verifiedArchiveRuntimeFunctionality,false);
assert.equal(proof.canonicalWrites,0);
assert.equal(proof.productionCertified,false);
for(const [i,p] of proof.parts.entries()){
 const original=v35.parts[i];
 assert.equal(p.index,i+1);
 assert.equal(p.filename,original.filename);
 assert.equal(p.driveId,original.driveId);
 assert.equal(p.observedBytes,original.bytes);
 assert.equal(p.observedSha256,original.sha256);
 assert.match(p.innerSha256,/^[a-f0-9]{64}$/);
 assert.equal(p.zipCrc,'PASS');
 assert.equal(p.historicalDigestMatch,true);
 if(i<17)assert.equal(p.innerMember,'OMEGA_SETUP/P'+String(i+1).padStart(2,'0')+'.bin');
 else assert.ok(p.innerMember.startsWith('OMEGA_SETUP/expansion/'));
}
assert.equal(ledger.independentArchiveByteWitnesses,79);
assert.equal(ledger.independentArchiveUnverifiedOtherListedParts,77);
assert.equal(ledger.recoveredV35SourceEvidence,'audit/omega-v35-full-source-acceptance-r953.json');
assert.ok(ledger.blockers.some(b=>b.id==='FAMILY_PARITY'&&b.state==='OPEN'));
const ui=readFileSync('src/DriveHistoricalRecoveryR936.tsx','utf8');
assert.ok(ui.includes('v35Proof.sourcePartsVerified'));
assert.ok(ui.includes('Installer/runtime behavior and GPU acceptance remain separate proof gates'));
console.log('R953 PASS: V35 20/20 ZIP original SHA/CRC, 17 main payloads and 3 expansions exact manifest matches; runtime and native proof held.');
