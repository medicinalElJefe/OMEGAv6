import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {stageRecoveryCapsulesR535} from '../scripts/r535-stage-recovery-capsules.mjs';
const root=fs.mkdtempSync(path.join(os.tmpdir(),'omega-r535-source-'));
const stagingRoot=fs.mkdtempSync(path.join(os.tmpdir(),'omega-r535-output-'));
try{
 const bytes='export const sourceRecovered=true;\n',sourcePath='donor.ts';
 fs.writeFileSync(path.join(root,sourcePath),bytes);
 const sourceSha256=createHash('sha256').update(bytes).digest('hex');
 const priorState={maxAutonomousGenerations:1,admittedSourceCapsules:['SG001'],roadmap:[{id:'SG001'}],currentCapsuleId:null};
 const manifest={capsules:[{id:'RG001',target:'src/generated/selfbuildR535/donor.ts',sourcePath,sourceSha256,prerequisites:['SG001']}]};
 const productionProof={exactPromotedSha:'a'.repeat(40),liveRuntimeSha:'a'.repeat(40),productionBrowserVerified:true};
 const input={root,priorState,manifest,productionProof,stagingRoot};
 const good=stageRecoveryCapsulesR535(input);
 assert.equal(good.status,'STAGED_FOR_GOVERNED_REVIEW');
 assert.equal(good.materialized,true);
 assert.equal(good.staged.length,1);
 assert.equal(good.staged[0].sha256,sourceSha256);
 assert.equal(fs.readFileSync(path.join(good.stagingDirectory,good.staged[0].stagedName),'utf8'),bytes);
 assert.equal(JSON.parse(fs.readFileSync(path.join(good.stagingDirectory,'manifest.json'),'utf8')).canonicalMutation,false);
 assert.equal(good.sourceMutation,false);
 assert.equal(good.executionClaimed,false);
 assert.equal(good.priorProductionProofIndependentlyVerified,false);
 assert.equal(stageRecoveryCapsulesR535({...input,stagingRoot:undefined}).status,'READY_FOR_EXPLICIT_STAGING');
 assert.equal(stageRecoveryCapsulesR535({...input,productionProof:null}).status,'HELD');
 assert.equal(stageRecoveryCapsulesR535({...input,manifest:{capsules:[]}}).status,'HELD');
 assert.equal(stageRecoveryCapsulesR535({...input,stagingRoot:root}).status,'HELD');
 assert.equal(stageRecoveryCapsulesR535({...input,manifest:{capsules:[{...manifest.capsules[0],target:'src/generated/selfbuildR535/../../worker.js'}]}}).status,'HELD');
 assert.equal(stageRecoveryCapsulesR535({...input,manifest:{capsules:[manifest.capsules[0],{...manifest.capsules[0],id:'RG002'}]}}).status,'HELD');
 const link=path.join(root,'linked.ts');fs.symlinkSync(path.join(root,sourcePath),link);
 assert.equal(stageRecoveryCapsulesR535({...input,manifest:{capsules:[{...manifest.capsules[0],sourcePath:'linked.ts'}]}}).status,'HELD');
 fs.writeFileSync(path.join(root,sourcePath),'tampered');
 assert.equal(stageRecoveryCapsulesR535(input).status,'HELD');
 assert.equal(fs.readFileSync(path.join(good.stagingDirectory,good.staged[0].stagedName),'utf8'),bytes,'prior verified staging must survive later source changes');
}finally{fs.rmSync(root,{recursive:true,force:true});fs.rmSync(stagingRoot,{recursive:true,force:true})}
console.log('R535 actual source-byte staging, tamper, confinement and refusal PASS');
