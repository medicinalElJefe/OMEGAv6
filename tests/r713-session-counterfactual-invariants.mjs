import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {DEFAULT_SCENARIO_R706} from '../src/relationalScenarioWorkbenchR706.mjs';
import {executeComputationalSessionR711} from '../src/computationalSessionR711.mjs';
import {compareComputationalSessionsR713} from '../src/computationalSessionComparisonR713.mjs';

const base=executeComputationalSessionR711(DEFAULT_SCENARIO_R706,{origin:'A',target:'B',mirrored:true});
const equal=compareComputationalSessionsR713(base.sessionJson,base.sessionJson);
assert.deepEqual(equal.changedSourceFrames,[]);
assert.equal(equal.changedNodeStates,0);
assert.equal(equal.changedRouteFrames,0);
assert.equal(equal.firstStateDivergence,null);
const modified=JSON.parse(JSON.stringify(DEFAULT_SCENARIO_R706));
modified.edgeFrames[1][0].kind='BLOCKED';
const altered=executeComputationalSessionR711(modified,{origin:'A',target:'B',mirrored:true});
const result=compareComputationalSessionsR713(base.sessionJson,altered.sessionJson);
assert.equal(result.schema,'OMEGA_COMPUTATIONAL_SESSION_COMPARISON_R713');
assert.equal(result.truthClass,'LOCAL_RECOMPUTED_COUNTERFACTUAL_ONLY');
assert.deepEqual(result.changedSourceFrames,[1]);
assert.equal(result.firstRouteDivergence,1);
assert.equal(result.routes[1].baselineReachable,true);
assert.equal(result.routes[1].interventionReachable,false);
assert.equal(result.routes[0].reachabilityChanged,false);
assert.equal(base.sourceScenario.edgeFrames[1][0].kind,'INGRESS','intervention must not mutate baseline');
assert.equal(result.states.length,4);
assert.equal(result.states[0].changedNodes.length,0,'fixed initial state must not diverge');
assert.throws(()=>compareComputationalSessionsR713(base.sessionJson,executeComputationalSessionR711(modified,{origin:'B',target:'A',mirrored:true}).sessionJson),/route endpoints/);
const different=JSON.parse(JSON.stringify(modified));
different.nodes[0].continuity=0.1;
assert.throws(()=>compareComputationalSessionsR713(base.sessionJson,executeComputationalSessionR711(different,{origin:'A',target:'B',mirrored:true}).sessionJson),/initial state/);
assert.throws(()=>compareComputationalSessionsR713(base.sessionJson,JSON.stringify({...JSON.parse(altered.sessionJson),authority:'PRODUCTION'})),/session envelope/);
