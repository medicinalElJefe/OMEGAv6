import fs from 'node:fs';
const must=(ok,msg)=>{if(!ok)throw new Error(msg)};
const registry=fs.readFileSync('src/navigationRegistry.ts','utf8');
const launcher=fs.readFileSync('src/OmegaLauncher.tsx','utf8');
const bridge=fs.readFileSync('src/ResponsiveRuntimeShell.tsx','utf8');
const shell=fs.readFileSync('src/SingleFrameRuntimeShellR27.tsx','utf8');
const workstation=fs.readFileSync('src/OmegaWorkstationFullV2.tsx','utf8');
const items=[...registry.matchAll(/id:'(\d+)',group:'([^']+)',name:'([^']+)',hint:'([^']+)',effect:'([^']+)',authority:'([^']+)'/g)].map(m=>({id:m[1],group:m[2],name:m[3],hint:m[4],effect:m[5],authority:m[6]}));
must(items.length===44,`navigation registry must contain exactly 44 surfaces, got ${items.length}`);
must(new Set(items.map(x=>x.id)).size===44,'navigation ids must be unique');
must(new Set(items.map(x=>x.name)).size===44,'navigation names must be unique');
for(const x of items){must(x.hint.length>=28,`navigation hint is too weak for ${x.name}`);must(['STUDIO','OPERATIONS','WORK','INTELLIGENCE','GOVERNANCE','SYSTEM'].includes(x.group),`invalid group ${x.group}`)}
must(launcher.includes('OMEGA_NAVIGATION')&&launcher.includes('LAUNCHER_SURFACES=OMEGA_NAVIGATION'),'NEXUS donor must use the shared navigation authority');
must(launcher.includes('data-authority={x.authority}')&&launcher.includes('data-effect={x.effect}'),'NEXUS donor must expose route truth classes');
const workBlock=(workstation.match(/export const OMEGA_SURFACES=\[(.*?)\] as const;/s)||[])[1]||'';
const workNames=[...workBlock.matchAll(/'([^']+)'/g)].map(x=>x[1]);
must(workNames.length===44,'active workstation must still register exactly 44 surfaces');
for(const x of items)must(workNames.includes(x.name),`shared navigation route missing from workstation registry: ${x.name}`);
const shellBlock=(shell.match(/R27_REGISTERED_SURFACES=\[(.*?)\] as const/s)||[])[1]||'';
const shellNames=[...shellBlock.matchAll(/'([^']+)'/g)].map(x=>x[1]);
must(shellNames.length===44,'R27 shell must retain exactly 44 registered destinations');
for(const x of items)must(shellNames.includes(x.name),`shared navigation registration missing from R27 shell: ${x.name}`);
must(bridge.includes('SingleFrameRuntimeShellR27')&&!bridge.includes('nav20-desktop'),'responsive compatibility path must mount only the R27 authority');
for(const name of workNames)must(items.some(x=>x.name===name),`workstation registers route absent from navigation authority: ${name}`);
console.log('NAVIGATION_REGISTRY_R27 PASS · one 44-surface registration universe · operational R27 shell');
