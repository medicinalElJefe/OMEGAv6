import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {SIZE,AGENTS,agentId,neighbors,createFabric,getAgent,stateValue,agentSnapshot,releaseAgent,submitTask,stepFabric,serializeFabricR888,restoreFabricR888,CHECKPOINT_SCHEMA_R888} from '../src/sphereAgentFabricR887.mjs';
const f=createFabric(), a=agentId(4,515), b=neighbors(a)[0], inner=144;
assert.equal(f.active.size,0);
// Reading any address must not consume bounded execution capacity.
for(let k=0;k<1024;k++)assert.equal(agentSnapshot(f,k%AGENTS,0,1).values.length,1);
assert.equal(f.active.size,0,'read-only probes may not allocate agents');
const sum=stateValue(f,a,inner)+stateValue(f,b,inner);
submitTask(f,{agent:a,kind:'EXCHANGE',target:b,inner,weight:.8});
const [receipt]=stepFabric(f);
assert.ok(Math.abs((stateValue(f,a,inner)+stateValue(f,b,inner))-sum)<1e-14);
assert.equal(receipt.conservationResidual,0);
assert.equal(releaseAgent(f,a),false,'mutated agent may not be evicted');
const before=serializeFabricR888(f);
const roundtrip=restoreFabricR888(before);
assert.equal(serializeFabricR888(roundtrip),before,'checkpoint is byte-for-byte canonical and exact');
assert.equal(stateValue(roundtrip,a,inner),stateValue(f,a,inner));
assert.equal(stateValue(roundtrip,b,inner),stateValue(f,b,inner));
assert.equal(roundtrip.active.get(b).inbox.length,1);
assert.equal(roundtrip.receipts.length,1);
submitTask(roundtrip,{agent:a,kind:'RELAX',inner:inner+1});
const queued=serializeFabricR888(roundtrip);
const recovered=restoreFabricR888(queued);
assert.equal(recovered.queue.length,1,'queued work restored');
assert.equal(stepFabric(recovered)[0].inner,inner+1,'restored work executes');
for(const bad of ['','not-json',JSON.stringify({schema:'wrong',state:{}}),before.replace('OMEGA_SPHERE_AGENT_CHECKPOINT_R888','WRONG_SCHEMA'),before.replace('"tick":1','"tick":2')])assert.throws(()=>restoreFabricR888(bad));
const exhausted=createFabric();
for(let k=0;k<511;k++)getAgent(exhausted,k);
const x=agentId(6,301),y=neighbors(x)[0];assert.ok(!exhausted.active.has(x)&&!exhausted.active.has(y));
submitTask(exhausted,{agent:x,kind:'EXCHANGE',target:y,inner:4});
const retained=exhausted.queue.length;
assert.throws(()=>stepFabric(exhausted),/budget exceeded/);
assert.equal(exhausted.queue.length,retained,'failed activation keeps task');
assert.equal(exhausted.active.size,511,'failed activation preserves active set');
assert.equal(exhausted.active.has(x),false);
assert.equal(exhausted.active.has(y),false);
assert.equal(exhausted.tick,0,'failed activation preserves tick');
const ui=readFileSync('src/SphereAgentInstrumentR887.tsx','utf8');
for(const token of ['setActiveInner(innerPage*144+i)','inner:activeInner','saveCheckpoint','restoreCheckpoint','serializeFabricR888','restoreFabricR888','aria-pressed={activeInner'])assert.ok(ui.includes(token),'R888 UI binding missing '+token);
assert.equal(CHECKPOINT_SCHEMA_R888,'OMEGA_SPHERE_AGENT_CHECKPOINT_R888');
console.log('R888 PASS · atomic refusal; no partial exchange; 511/512 capacity boundary; exact checkpoint roundtrip; queued task recovery; tamper rejection; no lossy state eviction; exact inner-cell targeting.');
