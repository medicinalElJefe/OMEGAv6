import assert from 'node:assert/strict';
import {piAxisNeighborsR742} from '../src/piAtlasTraversalR742.mjs';
import {computeConstrainedAtlasJourneyR744} from '../src/constrainedAtlasJourneyR744.mjs';
import {computeAtlasDetourR746,verifyAtlasDetourR746} from '../src/atlasDetourR746.mjs';
const COUNT=20736,field={count:COUNT},C=new Float32Array(COUNT);
for(let i=0;i<COUNT;i++)C[i]=(i%37)/36;
field.C=C;
const baseline=computeConstrainedAtlasJourneyR744(field,0,25,'C',[1],[12]);
const avoid=baseline.addresses.find(a=>a!==0&&a!==25&&a!==1);
assert.ok(Number.isInteger(avoid),'must have a non-stop route cell');
const result=computeAtlasDetourR746(field,baseline,avoid);
assert.ok(!result.detour.addresses.includes(avoid));
assert.deepEqual(result.detour,computeConstrainedAtlasJourneyR744(field,0,25,'C',[1],[12,avoid]));
