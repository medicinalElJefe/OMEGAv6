assert.equal(result.stepDelta,result.detour.steps-baseline.steps);
assert.equal(result.sharedAddressCount,new Set(result.detour.addresses.filter(a=>baseline.addresses.includes(a))).size);
assert.deepEqual(verifyAtlasDetourR746(JSON.stringify(result),field),result);
assert.throws(()=>verifyAtlasDetourR746(JSON.stringify({...result,costDelta:result.costDelta+1}),field),/differs/);
assert.throws(()=>verifyAtlasDetourR746(JSON.stringify({...result,detour:{...result.detour,steps:999}}),field),/differs/);
assert.throws(()=>computeAtlasDetourR746(field,baseline,0),/endpoint/);
assert.throws(()=>computeAtlasDetourR746(field,baseline,1),/ordered stop/);
assert.throws(()=>computeAtlasDetourR746(field,baseline,12),/already excluded/);
assert.throws(()=>computeAtlasDetourR746(field,baseline,20736),/outside/);
assert.throws(()=>computeAtlasDetourR746(field,baseline,piAxisNeighborsR742(0).find(a=>!baseline.addresses.includes(a)&&a!==12)),/must affect/);
assert.throws(()=>verifyAtlasDetourR746('{broken',field),/invalid JSON/);
assert.throws(()=>verifyAtlasDetourR746('x'.repeat(2097153),field),/size refused/);
