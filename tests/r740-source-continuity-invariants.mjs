import assert from 'node:assert/strict';
import {computeRouteBasinsR732} from '../src/routeBasinR732.mjs';
import {buildSourcePreimageIndexR739} from '../src/sourcePreimageR739.mjs';
import {proveSourceContinuityR740,SOURCE_CONTINUITY_SCHEMA_R740} from '../src/sourceContinuityR740.mjs';
const route=[1,2,1,4,5,4,3,7,7],graph=computeRouteBasinsR732(route);
const index=buildSourcePreimageIndexR739(route,graph);
const proof=proveSourceContinuityR740(index,graph);
assert.equal(proof.schema,SOURCE_CONTINUITY_SCHEMA_R740);
assert.equal(proof.nodeCount,9);assert.equal(proof.edgeCount,9);
assert.equal(proof.cycleNodes,5);assert.equal(proof.transientNodes,4);
assert.equal(proof.branchNodes,3);assert.equal(proof.zeroPreimageNodes,3);
assert.equal(proof.maxIndegree,2);assert.equal(proof.basinCount,3);
assert.equal(proof.basins.reduce((sum,b)=>sum+b.edgeCount,0),9);
assert.equal(proof.forwardInverseBijection,true);
assert.equal(proof.canonicalMutation,false);
const corrupt={...index,sources:index.sources.slice()};
corrupt.sources[0]=corrupt.sources[1];
assert.throws(()=>proveSourceContinuityR740(corrupt,graph),/bijection refused|edge bijection refused/);
const wrong={...index,offsets:index.offsets.slice()};
wrong.offsets[2]++;
assert.throws(()=>proveSourceContinuityR740(wrong,graph),/continuity mismatch|edge bijection refused/);
const n=20736,chain=new Uint32Array(n);
for(let i=0;i<n-1;i++)chain[i]=i+1;
chain[n-1]=n-1;
const full=proveSourceContinuityR740(buildSourcePreimageIndexR739(chain,computeRouteBasinsR732(chain)),computeRouteBasinsR732(chain));
assert.equal(full.nodeCount,n);assert.equal(full.edgeCount,n);
assert.equal(full.cycleNodes,1);assert.equal(full.transientNodes,n-1);
assert.equal(full.basinCount,1);assert.equal(full.maxIndegree,2);
assert.equal(full.basins[0].edgeCount,n);
console.log('R740 exact forward-inverse edge, basin, cycle and 20,736-state conservation PASS');
