import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {chromium} from 'playwright';
import {piAxisNeighborsR742,piAxisWitnessR742} from '../src/piAtlasTraversalR742.mjs';
const base=(process.env.OMEGA_E2E_URL||process.env.OMEGA_PUBLIC_URL||'http://127.0.0.1:4173').replace(/\/$/,'');
const expected=String(process.env.OMEGA_EXPECTED_SHA||'').trim();
if(expected){
 if(!/^[0-9a-f]{40}$/i.test(expected))throw Error('R742 exact promoted SHA required');
 const response=await fetch(base+'/omega-build-receipt.json?r742='+Date.now(),{headers:{'cache-control':'no-cache'}});
 if(!response.ok)throw Error('R742 receipt unavailable '+response.status);
 const receipt=await response.json();
 if(receipt?.schema!=='OMEGA_GOVERNED_BUILD_RECEIPT_V1'||receipt?.source?.sha!==expected||receipt?.promotion?.promotedMergeSha!==expected)
  throw Error('R742 exact production SHA mismatch');
}
const browser=await chromium.launch({headless:true});
try{
 for(const [device,viewport] of [['desktop',{width:1440,height:900}],['mobile',{width:390,height:844}]]){
  const context=await browser.newContext({viewport,deviceScaleFactor:device==='mobile'?2:1,acceptDownloads:true});
  const page=await context.newPage(),errors=[];
  page.on('pageerror',error=>errors.push(String(error)));
  try{
   await page.goto(base+'/?omega7=1&r742='+Date.now(),{waitUntil:'domcontentloaded',timeout:45000});
   await page.locator('.o7-app[data-omega7="true"]').waitFor({state:'visible',timeout:30000});
   await page.locator('.o7-nav-r519').getByRole('button',{name:'Explore'}).click();
   const portal=page.locator('.o7-r519-portal[data-r519-visual-navigation="EXPLORE"]');
   await portal.waitFor({state:'visible',timeout:20000});
   await portal.locator('button[data-r519-node="Atlas"]').click();
   await portal.locator('button[data-r519-launch="Atlas"]').click();
   const workspace=page.locator('.o7-science-workspace[data-route="Atlas"]');
   await workspace.waitFor({state:'visible',timeout:30000});
   const open=workspace.locator('.o7-open-instrument');
   if(await open.count())await open.click();
   const instrument=workspace.locator('[data-r732-basin-instrument="source-model"]');
   await instrument.waitFor({state:'visible',timeout:30000});
   await instrument.locator('[data-r732-run]').click();
   const explorer=instrument.locator('[data-r742-atlas]');
   await explorer.waitFor({state:'visible',timeout:45000});
   const source=Number(await workspace.getAttribute('data-address'));
   assert.ok(Number.isSafeInteger(source)&&source>=0&&source<20736,device+': invalid selected address');
   const target=piAxisNeighborsR742(source)[0];
   const expectedWitness=piAxisWitnessR742(source,target);
   await explorer.locator('[data-r742-target]').fill(String(target));
   assert.match(await explorer.locator('[data-r742-summary]').innerText(),/1 verified axis moves/);
   assert.equal((await explorer.locator('[data-r742-path]').innerText()).trim(),expectedWitness.path.join(' → '));
   const downloadPromise=page.waitForEvent('download',{timeout:20000});
   await explorer.locator('[data-r742-export]').click();
   const download=await downloadPromise;
   assert.equal(download.suggestedFilename(),'omega-r742-axis-witness.json');
   const witness=JSON.parse(await readFile(await download.path(),'utf8'));
   assert.deepEqual(witness,expectedWitness);
   const imported=explorer.locator('[data-r742-import]');
   await imported.setInputFiles({name:'axis.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(witness))});
   await explorer.locator('[data-r742-recovery]').filter({hasText:'VERIFIED · 1 recomputed axis moves'}).waitFor({state:'visible',timeout:10000});
   assert.equal(await explorer.locator('[data-r742-target]').inputValue(),String(target));
   await imported.setInputFiles({name:'tampered.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify({...witness,steps:2}))});
   await explorer.locator('[data-r742-recovery]').filter({hasText:'REFUSED · R742 witness differs'}).waitFor({state:'visible',timeout:10000});
   await explorer.locator('[data-r742-target]').fill('20736');
   assert.match(await explorer.locator('[data-r742-summary]').innerText(),/Enter a valid address/);
   const weighted=instrument.locator('[data-r743-metric-atlas]');
   await weighted.locator('[data-r743-target]').fill('20735');
   await weighted.locator('[data-r743-channel]').selectOption('C');
   await weighted.locator('[data-r743-summary]').filter({hasText:'optimized cost'}).waitFor({state:'visible',timeout:20000});
   const weightedDownloadPromise=page.waitForEvent('download',{timeout:20000});
   await weighted.locator('[data-r743-export]').click();
   const weightedDownload=await weightedDownloadPromise;
   assert.equal(weightedDownload.suggestedFilename(),'omega-r743-source-metric-route.json');
   const weightedWitness=JSON.parse(await readFile(await weightedDownload.path(),'utf8'));
   assert.equal(weightedWitness.from,source);
   assert.equal(weightedWitness.to,20735);
   assert.equal(weightedWitness.channel,'C');
   assert.equal(weightedWitness.addresses.at(-1),20735);
   assert.equal(weightedWitness.steps,weightedWitness.addresses.length-1);
   const weightedImport=weighted.locator('[data-r743-import]');
   await weightedImport.setInputFiles({name:'weighted.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(weightedWitness))});
   await weighted.locator('[data-r743-recovery]').filter({hasText:'VERIFIED · '+weightedWitness.steps+' source-metric axis moves'}).waitFor({state:'visible',timeout:20000});
   await weightedImport.setInputFiles({name:'tampered.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify({...weightedWitness,weightedCost:weightedWitness.weightedCost+1}))});
   await weighted.locator('[data-r743-recovery]').filter({hasText:'REFUSED · R743 route differs'}).waitFor({state:'visible',timeout:20000});
   await weighted.locator('[data-r743-step="1"]').click();
   assert.equal(Number(await workspace.getAttribute('data-address')),weightedWitness.addresses[1]);
   await weighted.locator('[data-r743-target]').fill('20736');
   assert.match(await weighted.locator('[data-r743-summary]').innerText(),/Enter a valid address/);
   const journey=instrument.locator('[data-r744-journey]');
   const journeySource=Number(await workspace.getAttribute('data-address'));
   const journeyNeighbors=piAxisNeighborsR742(journeySource);
   await journey.locator('[data-r744-target]').fill(String(journeyNeighbors[2]));
   await journey.locator('[data-r744-waypoints]').fill(String(journeyNeighbors[0]));
   await journey.locator('[data-r744-blocked]').fill(String(journeyNeighbors[6]));
   await journey.locator('[data-r744-channel]').selectOption('C');
   await journey.locator('[data-r744-summary]').filter({hasText:'2 optimized legs'}).waitFor({state:'visible',timeout:20000});
   const journeyDownloadPromise=page.waitForEvent('download',{timeout:20000});
   await journey.locator('[data-r744-export]').click();
   const journeyDownload=await journeyDownloadPromise;
   assert.equal(journeyDownload.suggestedFilename(),'omega-r744-constrained-journey.json');
   const journeyWitness=JSON.parse(await readFile(await journeyDownload.path(),'utf8'));
   assert.equal(journeyWitness.from,journeySource);
   assert.equal(journeyWitness.to,journeyNeighbors[2]);
   assert.deepEqual(journeyWitness.waypoints,[journeyNeighbors[0]]);
   assert.deepEqual(journeyWitness.blocked,[journeyNeighbors[6]]);
   assert.equal(journeyWitness.legs.length,2);
   assert.ok(!journeyWitness.addresses.includes(journeyNeighbors[6]));
   const journeyImport=journey.locator('[data-r744-import]');
   await journeyImport.setInputFiles({name:'journey.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(journeyWitness))});
   await journey.locator('[data-r744-recovery]').filter({hasText:'VERIFIED · 2 recomputed constrained legs'}).waitFor({state:'visible',timeout:20000});
   await journeyImport.setInputFiles({name:'tampered.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify({...journeyWitness,weightedCost:journeyWitness.weightedCost+1}))});
   await journey.locator('[data-r744-recovery]').filter({hasText:'REFUSED · R744 journey differs'}).waitFor({state:'visible',timeout:20000});
   // R745: same-browser checkpoint is explicitly saved, then refused on tampering.
   await journey.locator('[data-r745-save]').click();
   await journey.locator('[data-r745-status]').filter({hasText:'SAVED · 2 source-verified legs'}).waitFor({state:'visible',timeout:20000});
   const checkpointKey='omega.r745.local-atlas-journey.v1';
   const stored=await page.evaluate(key=>localStorage.getItem(key),checkpointKey);
   assert.ok(stored,'R745 must actually persist a checkpoint');
   const saved=JSON.parse(stored);
   assert.deepEqual(saved.journey,journeyWitness);
   await page.evaluate(([key,value])=>localStorage.setItem(key,value),[checkpointKey,JSON.stringify({...saved,journey:{...saved.journey,weightedCost:saved.journey.weightedCost+1}})]);
   await journey.locator('[data-r745-restore]').click();
   await journey.locator('[data-r745-status]').filter({hasText:'REFUSED · R744 journey differs'}).waitFor({state:'visible',timeout:20000});
   await page.evaluate(([key,value])=>localStorage.setItem(key,value),[checkpointKey,stored]);
   await journey.locator('[data-r745-restore]').click();
   await journey.locator('[data-r745-status]').filter({hasText:'VERIFIED · 2 freshly recomputed legs'}).waitFor({state:'visible',timeout:20000});
   await journey.locator('[data-r744-step="1"]').click();
   assert.equal(Number(await workspace.getAttribute('data-address')),journeyWitness.addresses[1]);
   await journey.locator('[data-r744-target]').fill('20736');
   assert.match(await journey.locator('[data-r744-summary]').innerText(),/REFUSED/);
   // Browser reload is a separate lifetime: recover only after recomputing the source.
   await page.reload({waitUntil:'domcontentloaded',timeout:45000});
   await page.locator('.o7-app[data-omega7="true"]').waitFor({state:'visible',timeout:30000});
   await page.locator('.o7-nav-r519').getByRole('button',{name:'Explore'}).click();
   const reloadPortal=page.locator('.o7-r519-portal[data-r519-visual-navigation="EXPLORE"]');
   await reloadPortal.locator('button[data-r519-node="Atlas"]').click();
   await reloadPortal.locator('button[data-r519-launch="Atlas"]').click();
   const reloadWorkspace=page.locator('.o7-science-workspace[data-route="Atlas"]');
   await reloadWorkspace.waitFor({state:'visible',timeout:30000});
   const reloadOpen=reloadWorkspace.locator('.o7-open-instrument');
   if(await reloadOpen.count())await reloadOpen.click();
   const reloadInstrument=reloadWorkspace.locator('[data-r732-basin-instrument="source-model"]');
   await reloadInstrument.locator('[data-r732-run]').click();
   const reloadJourney=reloadInstrument.locator('[data-r744-journey]');
   await reloadJourney.locator('[data-r745-restore]').click();
   await reloadJourney.locator('[data-r745-status]').filter({hasText:'VERIFIED · 2 freshly recomputed legs'}).waitFor({state:'visible',timeout:20000});
   assert.equal(Number(await reloadWorkspace.getAttribute('data-address')),journeyWitness.from);
   assert.equal(await reloadJourney.locator('[data-r744-target]').inputValue(),String(journeyWitness.to));
   assert.equal(await reloadJourney.locator('[data-r744-waypoints]').inputValue(),journeyWitness.waypoints.join(','));
   assert.equal(await reloadJourney.locator('[data-r744-blocked]').inputValue(),journeyWitness.blocked.join(','));
   await reloadJourney.locator('[data-r745-clear]').click();
   await reloadJourney.locator('[data-r745-status]').filter({hasText:'CLEARED · local checkpoint removed'}).waitFor({state:'visible',timeout:20000});
   assert.equal(await page.evaluate(key=>localStorage.getItem(key),checkpointKey),null);
   await reloadJourney.locator('[data-r745-restore]').click();
   await reloadJourney.locator('[data-r745-status]').filter({hasText:'REFUSED · R745 no saved journey'}).waitFor({state:'visible',timeout:20000});
   console.log('R745 '+device+' browser-persistent verified journey, tamper refusal, reload recovery and explicit clearing PASS');
   console.log('R744 '+device+' constrained source-metric journey, waypoints, exclusions, export, fresh recovery, tamper refusal, navigation and invalid target PASS');
   console.log('R743 '+device+' source-metric A* route, JSON export, fresh recovery, tamper refusal, live address navigation and invalid target PASS');
   if(await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth)>8)throw Error(device+': horizontal overflow');
   if(errors.length)throw Error(device+': browser errors '+errors.slice(0,3).join(' | '));
   console.log('R742 '+device+' executable axis traversal, exported JSON, verified recovery, tamper refusal, invalid target and containment PASS');
  }finally{await context.close()}
 }
}finally{await browser.close()}
