import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const workstation=read('src/OmegaWorkstationFull.tsx');
const shell=read('src/ResponsiveRuntimeShell.tsx');
const home=read('src/OmegaHome.tsx');
const app=read('src/App.tsx');
const navBlock=(workstation.match(/const NAV=\[(.*?)\] as const;type Panel/s)||[])[1]||'';
const surfaceBlock=(shell.match(/const SURFACES=\[(.*?)\] as const;/s)||[])[1]||'';
const nav=[...navBlock.matchAll(/\['([^']+)',[A-Za-z0-9_]+\]/g)].map(x=>x[1]);
const surfaces=[...surfaceBlock.matchAll(/\['([^']+)','(\d+)','([^']+)'\]/g)].map(x=>({group:x[1],id:x[2],name:x[3]}));
assert.equal(nav.length,44,'workstation must expose exactly 44 canonical surfaces');
assert.equal(new Set(nav).size,44,'workstation surface names must be unique');
assert.equal(surfaces.length,44,'responsive menu universe must expose exactly 44 surfaces');
assert.equal(new Set(surfaces.map(x=>x.id)).size,44,'responsive surface IDs must be unique');
assert.deepEqual(new Set(surfaces.map(x=>x.name)),new Set(nav),'desktop/mobile menu universe must match workstation navigation exactly');
for(const name of ['Command Center','Matter Traversal','Relativity','Earth Now','Forecast','SAI Lab'])assert.ok(nav.includes(name),`home launch target ${name} must exist in canonical navigation`);
assert.match(shell,/onClick=\{\(\)=>onNavigate\(name\)\}/,'menu buttons must execute the navigation callback');
assert.match(shell,/tab==='MENU'/,'mobile must expose the full menu universe');
assert.match(shell,/Search all 44 OMEGA surfaces/,'mobile menu must remain searchable');
assert.match(home,/\/api\/route-preview/,'home AI field must preserve route-before-generation preview');
assert.match(home,/\/api\/chat/,'home AI field must execute through the existing chat route');
assert.match(home,/onKeyDown=.*Enter/s,'home AI field must support keyboard submit');
assert.match(app,/omega-home-launch/,'workstation must provide a coherent return-to-home control');
assert.match(app,/setHome\(false\)/,'home navigation must enter the workstation');
console.log('navigation coherence PASS: 44/44 surfaces + home AI routing');
