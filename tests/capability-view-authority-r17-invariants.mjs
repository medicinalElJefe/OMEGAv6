import assert from 'node:assert/strict';
import fs from 'node:fs';
const cap=fs.readFileSync('src/capabilityAuthority.ts','utf8');
const nav=fs.readFileSync('src/navigationRegistry.ts','utf8');
const ws=fs.readFileSync('src/OmegaWorkstationFullV2.tsx','utf8');
const app=fs.readFileSync('src/App.tsx','utf8');
const bar=fs.readFileSync('src/OmegaViewAuthorityBar.tsx','utf8');
const css=fs.readFileSync('src/omegaViewAuthorityR17.css','utf8');
const names=[...cap.matchAll(/name:'([^']+)'/g)].map(x=>x[1]);
const navNames=[...nav.matchAll(/name:'([^']+)'/g)].map(x=>x[1]);
const routeBlock=(ws.match(/export const OMEGA_SURFACES=\[(.*?)\] as const;/s)||[])[1]||'';
const routeNames=[...routeBlock.matchAll(/'([^']+)'/g)].map(x=>x[1]);
assert.equal(names.length,44,'capability authority must declare exactly 44 applications');
assert.equal(new Set(names).size,44,'capability authority application names must be unique');
assert.deepEqual(new Set(names),new Set(navNames),'capability authority must cover shared navigation registry exactly');
assert.deepEqual(new Set(names),new Set(routeNames),'capability authority must cover active workstation routes exactly');
for(const v of ['FIELD','SURFACE','SKIN','GRAPH','ASSEMBLY','MATERIAL','EVIDENCE','CANON','TRAVERSAL'])assert(cap.includes(`'${v}'`),`missing canonical view ${v}`);
assert(cap.includes("implementation:'SHARED_SUITE'"),'registry must expose restoration debt rather than claiming every route is specialist-native');
assert(cap.includes("boundary:'DEVICE_PROOF'")&&cap.includes("boundary:'EVIDENCE_BOUND'")&&cap.includes("boundary:'PROVIDER_BOUND'"),'capability truth boundaries must remain explicit');
assert(cap.includes('does not create new evidence, a new physical dimension, or an independent state authority'),'same-packet epistemic boundary must be explicit');
assert(app.includes('OmegaViewAuthorityBar'),'view authority must be mounted in the live workstation');
assert(bar.includes("localStorage.setItem('omega.v6.viewLens',view)"),'selected view must persist');
assert(bar.includes("window.dispatchEvent(new CustomEvent('omega-view-change'"),'view change must emit a real runtime event');
assert(bar.includes('OMEGA_VIEW_LENSES.map'),'all canonical views must be actionable controls');
for(const v of ['field','surface','skin','graph','assembly','material','evidence','canon','traversal'])assert(css.includes(`data-omega-view='${v}'`),`view ${v} must have distinct presentation behavior`);
assert(!cap.includes('@appdeploy/client')&&!bar.includes('@appdeploy/client'),'R17 must remain provider-portable');
console.log('PASS capability-view-authority-r17-invariants · 44 routes + 9 same-packet views');
