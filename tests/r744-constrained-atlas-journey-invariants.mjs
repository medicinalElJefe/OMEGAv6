import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {piAxisNeighborsR742} from '../src/piAtlasTraversalR742.mjs';
import {computeMetricAtlasRouteR743} from '../src/sourceMetricAtlasRouteR743.mjs';
import {computeConstrainedAtlasJourneyR744,verifyConstrainedAtlasJourneyR744} from '../src/constrainedAtlasJourneyR744.mjs';
const COUNT=20736,field={count:COUNT,C:new Float32Array(COUNT)};
for(let i=0;i<COUNT;i++)field.C[i]=(i%37)/36;
const direct=computeConstrainedAtlasJourneyR744(field,0,20735,'C');
const baseline=computeMetricAtlasRouteR743(field,0,20735,'C');
assert.ok(Math.abs(direct.weightedCost-baseline.weightedCost)<1e-9,'unconstrained A* matches R743 optimum');
assert.deepEqual(direct.waypoints,[]);
assert.deepEqual(direct.blocked,[]);
assert.equal(direct.legs.length,1);
const via=[piAxisNeighborsR742(0)[0],piAxisNeighborsR742(0)[2]];
const blocked=[piAxisNeighborsR742(0)[6]];
const route=computeConstrainedAtlasJourneyR744(field,0,20735,'C',via,blocked);
assert.equal(route.legs.length,3);
assert.deepEqual(route.waypoints,via);
assert.deepEqual(route.blocked,blocked);
assert.equal(route.addresses[0],0);
assert.equal(route.addresses.at(-1),20735);
assert.ok(route.addresses.indexOf(via[0])>=0&&route.addresses.indexOf(via[1])>route.addresses.indexOf(via[0]));
assert.ok(!route.addresses.some(address=>blocked.includes(address)),'blocked address never traversed');
assert.equal(route.steps,route.addresses.length-1);
assert.equal(route.steps,route.legs.reduce((n,x)=>n+x.steps,0));
assert.ok(Math.abs(route.weightedCost-route.legs.reduce((n,x)=>n+x.weightedCost,0))<1e-9);
let measured=0;
for(let i=0;i<route.addresses.length-1;i++){
 const a=route.addresses[i],b=route.addresses[i+1];
 assert.ok(piAxisNeighborsR742(a).includes(b),'all journey edges are reversible neighbors');
 measured+=1+Math.abs(field.C[a]-field.C[b]);
}
assert.ok(Math.abs(route.weightedCost-measured)<1e-9,'full journey cost recomputed');
assert.deepEqual(verifyConstrainedAtlasJourneyR744(JSON.stringify(route),field),route);
assert.throws(()=>verifyConstrainedAtlasJourneyR744(JSON.stringify({...route,weightedCost:route.weightedCost+1}),field),/differs/);
assert.throws(()=>verifyConstrainedAtlasJourneyR744(JSON.stringify({...route,blocked:[...blocked,via[0]]}),field),/blocked/);
assert.throws(()=>computeConstrainedAtlasJourneyR744(field,0,1,'C',[],[0]),/blocked/);
assert.throws(()=>computeConstrainedAtlasJourneyR744(field,0,1,'C',[1],[1]),/blocked/);
assert.throws(()=>computeConstrainedAtlasJourneyR744(field,0,1,'C',[1,1],[]),/duplicate/);
assert.throws(()=>computeConstrainedAtlasJourneyR744(field,0,1,'C',[],[2,2]),/duplicate/);
assert.throws(()=>computeConstrainedAtlasJourneyR744(field,0,1,'C',[1,2,3,4,5]),/limit/);
assert.throws(()=>computeConstrainedAtlasJourneyR744(field,0,1,'C',[],Array.from({length:65},(_,i)=>i+100)),/limit/);
assert.throws(()=>computeConstrainedAtlasJourneyR744(field,0,20736),/outside/);
assert.throws(()=>computeConstrainedAtlasJourneyR744(field,0,1,'successorDeltaC'),/unsupported/);
assert.throws(()=>verifyConstrainedAtlasJourneyR744('{bad',field),/invalid JSON/);
assert.throws(()=>verifyConstrainedAtlasJourneyR744('x'.repeat(1048577),field),/size refused/);
const damaged={...field,C:new Float32Array(field.C)};
damaged.C[42]=NaN;
assert.throws(()=>computeConstrainedAtlasJourneyR744(damaged,0,1),/nonfinite/);
const isolated=piAxisNeighborsR742(0);
assert.equal(isolated.length,8);
assert.throws(()=>computeConstrainedAtlasJourneyR744(field,0,2,'C',[],isolated),/no admissible route/);
const ui=readFileSync(new URL('../src7/workspaces/RouteBasinInstrumentR732.tsx',import.meta.url),'utf8');
for(const marker of ['data-r744-journey','data-r744-target','data-r744-waypoints','data-r744-blocked','data-r744-channel','data-r744-summary','data-r744-path','data-r744-step','data-r744-export','data-r744-import','data-r744-recovery'])
 assert.ok(ui.includes(marker),'R744 UI missing '+marker);
console.log('R744 constrained A* source journeys, intermediate stops, exclusions, optimal baseline, cost conservation, refusal and verified recovery PASS');
