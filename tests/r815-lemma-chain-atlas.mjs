import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {atlasAddress,compileLemmaAtlasR815,LEMMAS} from '../scripts/r815-lemma-chain-atlas.mjs';
const hash=createHash('sha256').update('source bytes').digest('hex');
const evidence=Object.fromEntries(LEMMAS.map(lemma=>[lemma,{status:'PASS',proofSha256:hash}]));
const result=compileLemmaAtlasR815({evidence});
assert.equal(result.cellCount,20736);
assert.equal(result.logicalWorkerCount,144);
assert.equal(result.partitions.length,144);
assert.equal(result.partitions[0].start,0);
assert.equal(result.partitions.at(-1).end,20735);
assert.deepEqual(atlasAddress(20735),[11,11,11,11]);
assert.equal(result.decision,'ELIGIBLE_FOR_SEPARATE_GOVERNED_REVIEW');
assert.equal(result.actualCloudWorkersDispatched,0);
assert.equal(result.sourceMutationAuthorized,false);
for(let i=1;i<144;i++)assert.equal(result.partitions[i].previousHash,result.partitions[i-1].hash);
assert.equal(compileLemmaAtlasR815({evidence:{...evidence,RELEASE:{status:'PASS'}}}).decision,'HELD');
assert.equal(compileLemmaAtlasR815({evidence:{...evidence,RELEASE:{status:'FAIL',proofSha256:hash}}}).decision,'HELD');
assert.equal(compileLemmaAtlasR815({evidence}).chainRoot,result.chainRoot);
assert.throws(()=>atlasAddress(20736));
assert.throws(()=>compileLemmaAtlasR815({evidence,workerCount:20736}));
console.log('R815 PASS · 20,736 addresses · 144 logical partitions · 12 lemma gates · hash continuity · refusal');
